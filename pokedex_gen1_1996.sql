SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS pokedex_gen1 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pokedex_gen1;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS efectividad_tipos;
DROP TABLE IF EXISTS evoluciones;
DROP TABLE IF EXISTS pokemon_tipos;
DROP TABLE IF EXISTS pokemon;
DROP TABLE IF EXISTS tipos;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE tipos (
  id_tipo TINYINT UNSIGNED PRIMARY KEY,
  nombre VARCHAR(20) NOT NULL UNIQUE,
  categoria_ataque ENUM('fisico','especial') NOT NULL
) ENGINE=InnoDB;

CREATE TABLE pokemon (
  numero_pokedex SMALLINT UNSIGNED PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  slug VARCHAR(40) NOT NULL UNIQUE,
  ps_base SMALLINT UNSIGNED NOT NULL,
  ataque_base SMALLINT UNSIGNED NOT NULL,
  defensa_base SMALLINT UNSIGNED NOT NULL,
  especial_base SMALLINT UNSIGNED NOT NULL,
  velocidad_base SMALLINT UNSIGNED NOT NULL,
  CONSTRAINT chk_pokedex_151 CHECK (numero_pokedex BETWEEN 1 AND 151)
) ENGINE=InnoDB;

CREATE TABLE pokemon_tipos (
  numero_pokedex SMALLINT UNSIGNED NOT NULL,
  id_tipo TINYINT UNSIGNED NOT NULL,
  posicion TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (numero_pokedex, posicion),
  CONSTRAINT uq_pokemon_tipo UNIQUE (numero_pokedex, id_tipo),
  FOREIGN KEY (numero_pokedex) REFERENCES pokemon(numero_pokedex) ON DELETE CASCADE,
  FOREIGN KEY (id_tipo) REFERENCES tipos(id_tipo),
  CONSTRAINT chk_tipo_posicion CHECK (posicion IN (1, 2))
) ENGINE=InnoDB;

CREATE TABLE evoluciones (
  id_evolucion SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  numero_origen SMALLINT UNSIGNED NOT NULL,
  numero_destino SMALLINT UNSIGNED NOT NULL,
  metodo ENUM('nivel', 'piedra', 'intercambio') NOT NULL,
  nivel_requerido TINYINT UNSIGNED NULL,
  piedra VARCHAR(20) NULL,
  CONSTRAINT uq_evolucion UNIQUE (numero_origen, numero_destino),
  FOREIGN KEY (numero_origen) REFERENCES pokemon(numero_pokedex),
  FOREIGN KEY (numero_destino) REFERENCES pokemon(numero_pokedex),
  CONSTRAINT chk_evolucion_diferente CHECK (numero_origen <> numero_destino)
) ENGINE=InnoDB;

CREATE TABLE efectividad_tipos (
  tipo_ataque_id TINYINT UNSIGNED NOT NULL,
  tipo_defensa_id TINYINT UNSIGNED NOT NULL,
  multiplicador DECIMAL(3,1) NOT NULL,
  PRIMARY KEY (tipo_ataque_id, tipo_defensa_id),
  FOREIGN KEY (tipo_ataque_id) REFERENCES tipos(id_tipo),
  FOREIGN KEY (tipo_defensa_id) REFERENCES tipos(id_tipo),
  CONSTRAINT chk_multiplicador CHECK (multiplicador IN (0.0,0.5,1.0,2.0))
) ENGINE=InnoDB;

